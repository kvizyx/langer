//! Compiles MediaPipe's Plan 9 rune tables (`vendor/mediapipe/runetypebody.h`, vendored unmodified) into
//! Rust constants, so the tables come straight from the upstream file.

use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

use anyhow::{Context as _, ensure};

const SOURCE: &str = "vendor/mediapipe/runetypebody.h";

/// Plan 9 stores case deltas offset by 2^20 so that they are positive.
const DELTA_BIAS: i64 = 1 << 20;

/// `(C array, Rust constant, row layout, documentation)` of every table.
const TABLES: [(&str, &str, Layout, &str); 5] = [
    (
        "__isalphar",
        "ALPHA_RANGES",
        Layout::Ranges,
        "Inclusive ranges of alphabetic code points.",
    ),
    (
        "__isalphas",
        "ALPHA_SINGLES",
        Layout::Singles,
        "Single alphabetic code points.",
    ),
    (
        "__tolowerr",
        "LOWER_RANGES",
        Layout::RangeDeltas,
        "Ranges lowercased by adding a delta.",
    ),
    (
        "__tolowerp",
        "LOWER_PAIRS",
        Layout::RangeDeltas,
        "Ranges where every other code point, from the first, is lowercased by a delta.",
    ),
    (
        "__tolowers",
        "LOWER_SINGLES",
        Layout::SingleDeltas,
        "Single code points lowercased by a delta.",
    ),
];

#[derive(Clone, Copy)]
enum Layout {
    /// `start, end`
    Ranges,
    /// `code_point`
    Singles,
    /// `start, end, biased_delta`
    RangeDeltas,
    /// `code_point, biased_delta`
    SingleDeltas,
}

fn main() -> anyhow::Result<()> {
    println!("cargo::rerun-if-changed={SOURCE}");

    let header = fs::read_to_string(SOURCE).with_context(|| format!("cannot read {SOURCE}"))?;

    let mut out = format!("// Generated by build.rs from {SOURCE}.\n");
    for (array, constant, layout, doc) in TABLES {
        let values = array_values(&header, array)?;
        let width = match layout {
            Layout::Singles => 1,
            Layout::Ranges | Layout::SingleDeltas => 2,
            Layout::RangeDeltas => 3,
        };

        ensure!(
            !values.is_empty() && values.len().is_multiple_of(width),
            "{SOURCE}: {array} has {} values, expected a multiple of {width}",
            values.len()
        );

        let (ty, rows): (&str, Vec<String>) = match layout {
            Layout::Singles => ("u32", values.iter().map(|v| format!("{v:#06X}")).collect()),
            // The length is a multiple of the width, so the chunks have no remainder.
            Layout::Ranges => (
                "(u32, u32)",
                values
                    .as_chunks()
                    .0
                    .iter()
                    .map(|[start, end]| format!("({start:#06X}, {end:#06X})"))
                    .collect(),
            ),
            Layout::RangeDeltas => (
                "(u32, u32, i32)",
                values
                    .as_chunks()
                    .0
                    .iter()
                    .map(|[start, end, delta]| format!("({start:#06X}, {end:#06X}, {})", delta - DELTA_BIAS))
                    .collect(),
            ),
            Layout::SingleDeltas => (
                "(u32, i32)",
                values
                    .as_chunks()
                    .0
                    .iter()
                    .map(|[code_point, delta]| format!("({code_point:#06X}, {})", delta - DELTA_BIAS))
                    .collect(),
            ),
        };

        // Lookups binary-search on the first column.
        ensure!(
            values.iter().step_by(width).is_sorted(),
            "{SOURCE}: {array} is not sorted"
        );

        writeln!(out, "/// {doc} (`{array}`)")?;
        writeln!(out, "pub(crate) const {constant}: &[{ty}] = &[{}];", rows.join(", "))?;
    }

    let path = PathBuf::from(env::var_os("OUT_DIR").context("cargo did not set OUT_DIR")?).join("unicode_tables.rs");
    fs::write(path, out).context("cannot write to OUT_DIR")?;

    Ok(())
}

/// Values of `static Rune <name>[] = { ... };` in `header`.
fn array_values(header: &str, name: &str) -> anyhow::Result<Vec<i64>> {
    let declaration = format!("static Rune {name}[] = {{");

    let (_, body) = header
        .split_once(&declaration)
        .with_context(|| format!("{SOURCE}: no array {name}"))?;
    let (body, _) = body
        .split_once("};")
        .with_context(|| format!("{SOURCE}: {name} is not closed"))?;

    body.split(',')
        .map(str::trim)
        .filter(|v| !v.is_empty())
        .map(|v| {
            let parsed = match v.strip_prefix("0x") {
                Some(hex) => i64::from_str_radix(hex, 16),
                None => v.parse(),
            };

            parsed.with_context(|| format!("{SOURCE}: invalid value {v:?} in {name}"))
        })
        .collect()
}
