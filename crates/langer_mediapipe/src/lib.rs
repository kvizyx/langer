//! Pure Rust inference for MediaPipe's text language detector.
//!
//! [`Detector`] runs [MediaPipe's language detector](https://ai.google.dev/edge/mediapipe/solutions/text/language_detector)
//! model (110 languages, ~300 KiB) without TensorFlow Lite or MediaPipe. The model is bundled
//! with the crate; [`Detector::from_bytes`] loads other files with the same structure.
//!
//! The model hashes character n-grams of the text (`NGramHash`), averages k-means compressed
//! embeddings of the hashes (`KmeansEmbeddingLookup`), and classifies the result with
//! fully connected layers that have `i8` weights. Each step mirrors the MediaPipe custom ops
//! and the TFLite reference kernels, including MediaPipe's Plan 9 Unicode tables and
//! TFLite's dynamic input quantization, so predictions match MediaPipe's.
//!
//! # Examples
//!
//! ```
//! use langer_mediapipe::Detector;
//!
//! let detector = Detector::new()?;
//! let best = detector.predict("Привет, как дела?", 1)?[0];
//! assert_eq!(best.language, "ru");
//! assert!(best.probability > 0.9);
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```

